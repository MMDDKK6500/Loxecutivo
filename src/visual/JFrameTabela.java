    private void removerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removerActionPerformed
        if (tabela.getSelectedRows().length == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum dado selecionado", "Erro", JOptionPane.WARNING_MESSAGE);
            return;
        }        
        DaoEventos dev = new DaoEventos();
        DaoViagens dvi = new DaoViagens();
        DaoMotoristas dm = new DaoMotoristas();
        DaoVeiculos dv = new DaoVeiculos();
        DaoPassageiros dp = new DaoPassageiros();
        DaoEnderecos den = new DaoEnderecos();
        
        String[] ids = new String[tabela.getSelectedRowCount()];
        int indexids = 0;
        
        // O(n²) - duas for nested
        for (int y : tabela.getSelectedRows()) {
            int x = 0;
            switch (SelecaoTabela.getSelectedIndex()) {
                case 0:
                    x = den.idIndex;
                    break;
                case 1:
                    x = dev.idIndex;
                    break;
                case 2:
                    x = dm.idIndex;;
                    break;
                case 3:
                    x = dp.idIndex;
                    break;                
                case 4:
                    x = dv.idIndex;
                    break;
                case 5:
                    x = dvi.idIndex;
                    break;
            }
            String into = String.valueOf(tabela.getModel().getValueAt(y, x - 1));
            ids[indexids] = into;
            indexids++;
        }
        
        if (ids.length == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum dado selecionado", "Erro", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            switch (SelecaoTabela.getSelectedIndex()) {
                case 0:
                    //Endereços
                    if (den.checkDependencias(ids)) return;
                    break;
                case 1:
                    //Eventos
                    if (dev.checkDependencias(ids)) return;
                    break;
                case 2:
                    //Motoristas
                    if (dm.checkDependencias(ids)) return;
                    break;
                case 3:
                    //Passageiros
                    break;                
                case 4:
                    //Veiculos
                    if (dv.checkDependencias(ids)) return;
                    break;
                case 5:
                    //Viagens
                    if (dvi.checkDependencias(ids)) return;
                    break;
            }
        } catch (Exception ex) {
            return;
        }
        
        
        int confirmacao = JOptionPane.showConfirmDialog(this, "Certeza que quer apagar os dados com ids:\n" + Arrays.toString(ids), "Confirmação", JOptionPane.ERROR_MESSAGE);
        if (confirmacao == JOptionPane.YES_OPTION) {
            ResultSet rs;
            for (String id : ids) {
            switch (SelecaoTabela.getSelectedIndex()) {
                case 0:
                    den.removeByID(Integer.parseInt(id));
                    break;
                case 1:
                    dev.removeByID(Integer.parseInt(id));
                    break;
                case 2:
                    dm.removeByID(Integer.parseInt(id));
                    break;
                case 3:
                    dp.removeByID(Integer.parseInt(id));
                    break;                
                case 4:
                    dv.removeByID(id);
                    break;
                case 5:
                    dvi.removeByID(Integer.parseInt(id));
                    break;
                }
            }
            updateTabela();
        }
    }//GEN-LAST:event_removerActionPerformed

    private void alterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_alterarActionPerformed
        if (tabela.getSelectedRows().length == 0) {
            JOptionPane.showMessageDialog(this, "Nenhum dado selecionado", "Erro", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        for (int i : tabela.getSelectedRows()) {
            switch (SelecaoTabela.getSelectedIndex()) {
                case 0:
                    DaoEnderecos den = new DaoEnderecos();
                    int denId = (int)tabela.getModel().getValueAt(i, den.idIndex - 1);
                    Endereco e = den.getEndereco(denId);
                    JDialogEndereco endereco = new JDialogEndereco(true, e);
                    endereco.setVisible(true);
                    break;
                case 1:
                    DaoEventos dev = new DaoEventos();
                    int devId = (int)tabela.getModel().getValueAt(i, dev.idIndex - 1);
                    Evento ev = dev.getEvento(devId);
                    JDialogEvento evento = new JDialogEvento(true, ev);
                    evento.setVisible(true);
                    break;
                case 2:
                    DaoMotoristas dm = new DaoMotoristas();
                    int moId = (int)tabela.getModel().getValueAt(i, dm.idIndex - 1);
                    Motorista mo = dm.getMotorista(moId);
                    JDialogMotorista motoristas = new JDialogMotorista(true, mo);
                    motoristas.setVisible(true);
                    break;
                case 3:
                    DaoPassageiros dap = new DaoPassageiros();
                    int paId = (int)tabela.getModel().getValueAt(i, dap.idIndex - 1);
                    Passageiro pa = dap.getPassageiro(paId);
                    JDialogPassageiro passageiro = new JDialogPassageiro(true, pa);
                    passageiro.setVisible(true);
                    break;                
                case 4:
                    DaoVeiculos dav = new DaoVeiculos();
                    String veId = String.valueOf(tabela.getModel().getValueAt(i, dav.idIndex - 1));
                    Veiculo ve = dav.getVeiculo(veId);
                    JDialogVeiculo veiculo = new JDialogVeiculo(true, ve);
                    veiculo.setVisible(true);
                    break;
                case 5:
                    DaoViagens dvi = new DaoViagens();
                    int viId = (int)tabela.getModel().getValueAt(i, dvi.idIndex - 1);
                    Viagem vi = dvi.getViagem(viId);
                    JDialogViagem viagem = new JDialogViagem(true, vi);
                    viagem.setVisible(true);
                    break;
                default:
                    JOptionPane.showMessageDialog(this, "Nenhuma tabela selecionada", "Erro", JOptionPane.WARNING_MESSAGE);
                    break;
            }
        }
        updateTabela();
    }//GEN-LAST:event_alterarActionPerformed

